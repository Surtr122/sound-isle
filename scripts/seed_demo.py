"""Seed the synthetic demo library with tags, favorites and nested drawers.

The demo folders are generated by make_demo_assets.py and make_demo_library.py.
This script only talks to the local API; it never touches real user files.
"""

from __future__ import annotations

import json
import os
import urllib.request

BASE = os.environ.get("BASE", "http://127.0.0.1:8787").rstrip("/")


def call(path: str, payload=None):
    data = None if payload is None else json.dumps(payload, ensure_ascii=False).encode("utf-8")
    request = urllib.request.Request(BASE + path, data=data, method="POST" if data else "GET")
    if data:
        request.add_header("Content-Type", "application/json")
    with urllib.request.urlopen(request) as response:
        return json.loads(response.read().decode("utf-8"))


state = call("/api/state")
tracks = state["library"]["tracks"]
by_title = {track["title"]: track for track in tracks}

tags = {
    "晨雾": ["夜晚", "通勤"],
    "潮汐": ["夜晚", "通勤"],
    "海面": ["夜晚", "学习"],
    "海浪 01": ["环境", "自然"],
    "风声 02": ["环境", "自然"],
    "攻击 01": ["战斗"],
    "荒原旅人": ["主角", "待整理"],
    "守望者": ["主角", "待整理"],
    "废弃站台": ["场景", "待优化"],
    "站台": ["工程"],
    "混凝土_albedo": ["材质"],
    "蒙皮小人": ["主角", "待整理"],
}
for title, names in tags.items():
    track = by_title.get(title)
    if track:
        call("/api/tags/add", {"ids": [track["id"]], "tags": names})

for title in ("晨雾", "荒原旅人", "蒙皮小人"):
    track = by_title.get(title)
    if track:
        call("/api/favorites", {"ids": [track["id"]], "favorite": True})


def ensure_category(name: str, parent: str, accent: str) -> dict:
    state = call("/api/state")
    for category in state["library"]["categories"]:
        if category.get("custom") and category.get("name") == name and (category.get("parent") or "") == parent:
            return category
    return call("/api/categories/create", {"name": name, "parent": parent, "accent": accent})["category"]


sfx_child = ensure_category("脚步细节", "sfx", "#C65D3B")
anim_child = ensure_category("待机细节", "animation", "#B08A45")

foot = by_title.get("脚步 01")
if foot:
    call("/api/memberships/set", {"ids": [foot["id"]], "categories": ["sfx", sfx_child["key"]]})
idle = by_title.get("待机循环")
if idle:
    call("/api/memberships/set", {"ids": [idle["id"]], "categories": ["animation", anim_child["key"]]})

latest = call("/api/state")["library"]
print(json.dumps({
    "tracks": latest["stats"]["total"],
    "tags": len(latest["tags"]),
    "favorites": latest["stats"]["favorites"],
    "categories": len(latest["categories"]),
}, ensure_ascii=False, indent=2))
